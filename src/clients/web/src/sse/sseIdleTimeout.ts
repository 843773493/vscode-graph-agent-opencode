/**
 * 浏览器客户端 SSE 长连接的空闲阈值：全仓唯一来源。
 *
 * 服务端所有长连 SSE 流（Trace 流、Turn 消息流、workspace 文件流、会话活动流）
 * 都按远小于该阈值的间隔发送心跳注释帧。客户端读循环必须拿到一个大于心跳间隔的
 * 上限，才能区分「对方还活着、只是暂时没有业务事件」与「对方真的一个字节都不再发」
 * （进程被 SIGSTOP、TCP 半开、网络黑洞）。没有上限时后者会让页面无限静默挂起、
 * 毫无反馈，违反「程序绝不能默默失败」。
 *
 * 取 45s = 3 个 15s 心跳周期：容忍单次心跳抖动或丢包而不会误判断开，同时保证真实
 * 故障在分钟级内可见。该值必须严格大于服务端心跳间隔，否则健康空闲流会被误判。
 */
export const SSE_IDLE_TIMEOUT_MS = 45_000;
